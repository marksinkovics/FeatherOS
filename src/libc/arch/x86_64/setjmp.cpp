// File-level assembly, so no compiler-generated prologue changes the registers being saved.
// jmp_buf: rbx, rbp, r12-r15, the caller's rsp, and the return address. longjmp makes setjmp
// appear to return value, or 1 if value is 0.
asm(".text\n"
    ".global setjmp\n"
    ".type setjmp, @function\n"
    "setjmp:\n\t"
    "movq %rbx, 0(%rdi)\n\t"
    "movq %rbp, 8(%rdi)\n\t"
    "movq %r12, 16(%rdi)\n\t"
    "movq %r13, 24(%rdi)\n\t"
    "movq %r14, 32(%rdi)\n\t"
    "movq %r15, 40(%rdi)\n\t"
    "leaq 8(%rsp), %rdx\n\t"
    "movq %rdx, 48(%rdi)\n\t"
    "movq (%rsp), %rdx\n\t"
    "movq %rdx, 56(%rdi)\n\t"
    "xorl %eax, %eax\n\t"
    "ret\n"
    ".size setjmp, . - setjmp\n"
    "\n"
    ".global longjmp\n"
    ".type longjmp, @function\n"
    "longjmp:\n\t"
    "movl %esi, %eax\n\t"
    "testl %eax, %eax\n\t"
    "jnz 1f\n\t"
    "incl %eax\n"
    "1:\n\t"
    "movq 0(%rdi), %rbx\n\t"
    "movq 8(%rdi), %rbp\n\t"
    "movq 16(%rdi), %r12\n\t"
    "movq 24(%rdi), %r13\n\t"
    "movq 32(%rdi), %r14\n\t"
    "movq 40(%rdi), %r15\n\t"
    "movq 48(%rdi), %rsp\n\t"
    "jmpq *56(%rdi)\n"
    ".size longjmp, . - longjmp\n");
