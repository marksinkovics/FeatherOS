// File-level assembly, so no compiler-generated prologue changes the registers being saved.
// jmp_buf: x19-x28, the frame pointer x29, the return address x30, and sp. longjmp makes setjmp
// appear to return value, or 1 if value is 0.
asm(".text\n"
    ".global setjmp\n"
    ".type setjmp, %function\n"
    "setjmp:\n\t"
    "stp x19, x20, [x0, #0]\n\t"
    "stp x21, x22, [x0, #16]\n\t"
    "stp x23, x24, [x0, #32]\n\t"
    "stp x25, x26, [x0, #48]\n\t"
    "stp x27, x28, [x0, #64]\n\t"
    "stp x29, x30, [x0, #80]\n\t"
    "mov x2, sp\n\t"
    "str x2, [x0, #96]\n\t"
    "mov w0, #0\n\t"
    "ret\n"
    ".size setjmp, . - setjmp\n"
    "\n"
    ".global longjmp\n"
    ".type longjmp, %function\n"
    "longjmp:\n\t"
    "ldp x19, x20, [x0, #0]\n\t"
    "ldp x21, x22, [x0, #16]\n\t"
    "ldp x23, x24, [x0, #32]\n\t"
    "ldp x25, x26, [x0, #48]\n\t"
    "ldp x27, x28, [x0, #64]\n\t"
    "ldp x29, x30, [x0, #80]\n\t"
    "ldr x2, [x0, #96]\n\t"
    "mov sp, x2\n\t"
    "cmp w1, #0\n\t"
    "csinc w0, w1, wzr, ne\n\t"
    "ret\n"
    ".size longjmp, . - longjmp\n");
