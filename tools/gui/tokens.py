#!/usr/bin/env python3
"""Writes src/user/ui/tokens.{h,cpp} from tools/gui/tokens.json.

tokens.py          write the two files
tokens.py --check  compare them with what the JSON produces
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TOKENS_JSON = HERE / "tokens.json"
OUT_DIR = ROOT / "src" / "user" / "ui"

COLOR_TOKENS = (
    "desk",
    "bar",
    "surface",
    "raised",
    "sunken",
    "line",
    "text",
    "muted",
    "accent",
    "on_accent",
    "accent_soft",
    "ok",
    "warn",
    "bad",
    "info",
    "focus",
)

BANNER = (
    "// Generated by tools/gui/tokens.py from tools/gui/tokens.json. "
    "Do not edit.\n"
)


def load() -> dict:
    return json.loads(TOKENS_JSON.read_text(encoding="utf-8"))


def parse_hex(value: str) -> int:
    if len(value) != 7 or value[0] != "#":
        raise ValueError(f"not a #rrggbb colour: {value!r}")
    return int(value[1:], 16)


def color_literal(rgb: str, alpha: int = 255) -> str:
    return f"0x{alpha:02X}{parse_hex(rgb):06X}"


def camel(entry: dict) -> str:
    return entry.get("cpp") or entry["id"].capitalize()


def pascal(snake: str) -> str:
    return "".join(part.capitalize() for part in snake.split("_"))


def enum_block(name: str, names: list[str]) -> list[str]:
    lines = [f"enum class {name} : uint8_t", "{"]
    lines += [f"    {item}," for item in names]
    lines += ["};", ""]
    return lines


def render_header(tokens: dict) -> str:
    themes = tokens["themes"]
    families = tokens["families"]
    accents = tokens["accents"]
    shadows = tokens["shadows"]
    roles = list(tokens["type_roles"])
    apps = tokens["app_tiles"]
    metrics = tokens["metrics"]
    durations = tokens["durations_ms"]

    out = [
        BANNER.rstrip("\n"),
        "#ifndef FEATHEROS_USER_UI_TOKENS_H",
        "#define FEATHEROS_USER_UI_TOKENS_H",
        "",
        '#include "../graphics/color.h"',
        "",
        "#include <stdint.h>",
        "",
        "namespace FeatherOS::UI",
        "{",
        "",
    ]
    out += enum_block("ThemeId", [camel(t) for t in themes])
    out += enum_block("Family", [camel(f) for f in families])
    out += [
        "enum class Mode : uint8_t",
        "{",
        "    Dark,",
        "    Light,",
        "    Auto,",
        "};",
        "",
    ]
    out += enum_block("AccentId", [camel(a) for a in accents])
    out += enum_block("ShadowRole", [pascal(s["id"]) for s in shadows])
    out += enum_block("TypeRole", [pascal(r) for r in roles])
    out += enum_block("AppId", [camel(a) for a in apps])

    out += [
        f"constexpr uint32_t ThemeCount = {len(themes)};",
        f"constexpr uint32_t FamilyCount = {len(families)};",
        f"constexpr uint32_t AccentCount = {len(accents)};",
        f"constexpr uint32_t ShadowRoleCount = {len(shadows)};",
        f"constexpr uint32_t TypeRoleCount = {len(roles)};",
        f"constexpr uint32_t AppCount = {len(apps)};",
        "",
    ]
    for key, value in metrics.items():
        out.append(f"constexpr int32_t {pascal(key)} = {value};")
    out.append("")
    for key, value in durations.items():
        out.append(f"constexpr uint32_t Duration{pascal(key)}Ms = {value};")
    easing = ", ".join(str(v) for v in tokens["easing_milli"])
    out += [
        f"inline constexpr int32_t EasingMilli[4] = {{{easing}}};",
        "",
        "struct Theme",
        "{",
        "    ThemeId id;",
        "    Family family;",
        "    bool dark;",
        "    const char* name;",
    ]
    out += [f"    Graphics::Color {token};" for token in COLOR_TOKENS]
    out += [
        "    Graphics::Color wallpaper_1;",
        "    Graphics::Color wallpaper_2;",
        "    Graphics::Color wallpaper_3;",
        "    Graphics::Color wallpaper_feather;",
        "    Graphics::Color shadow;",
        "};",
        "",
        "struct ShadowSpec",
        "{",
        "    int32_t offset_y;",
        "    int32_t blur;",
        "    int32_t corner_radius;",
        "};",
        "",
        "const Theme& BaseTheme(ThemeId id);",
        "Theme WithAccent(const Theme& base, AccentId accent);",
        "ThemeId ResolveTheme(Family family, Mode mode, uint32_t hour);",
        "const char* FamilyName(Family family);",
        "const char* AccentName(AccentId accent);",
        "const ShadowSpec& ShadowSpecOf(ShadowRole role);",
        "const char* FontName(TypeRole role);",
        "Graphics::Color AppTileColor(AppId app);",
        "",
        "} // namespace FeatherOS::UI",
        "",
        "#endif",
        "",
    ]
    return "\n".join(out)


def theme_entry(theme: dict) -> list[str]:
    wallpaper = theme["wallpaper"]
    shadow = theme["shadow"]
    lines = [
        "    {",
        f"        .id = ThemeId::{camel(theme)},",
        f"        .family = Family::{theme['family_cpp']},",
        f"        .dark = {'true' if theme['dark'] else 'false'},",
        f'        .name = "{theme["name"]}",',
    ]
    for token in COLOR_TOKENS:
        lines.append(
            f"        .{token} = {color_literal(theme['colors'][token])},"
        )
    lines += [
        f"        .wallpaper_1 = {color_literal(wallpaper['w1'])},",
        f"        .wallpaper_2 = {color_literal(wallpaper['w2'])},",
        f"        .wallpaper_3 = {color_literal(wallpaper['w3'])},",
        "        .wallpaper_feather = "
        f"{color_literal(wallpaper['wf'], wallpaper['wf_alpha'])},",
        f"        .shadow = {color_literal(shadow['rgb'], shadow['alpha'])},",
        "    },",
    ]
    return lines


SOURCE_TYPES = """\
struct AccentShade
{
    Graphics::Color accent;
    Graphics::Color on_accent;
};

struct FamilyThemes
{
    const char* name;
    ThemeId dark;
    ThemeId light;
};
"""  # noqa: E501

SOURCE_HELPERS = """\
uint32_t Channel(Graphics::Color color, uint32_t shift)
{
    return (color >> shift) & 0xFFU;
}

Graphics::Color Mix(Graphics::Color top, Graphics::Color under, uint32_t percent)
{
    uint32_t result = 0xFF000000U;
    for (uint32_t shift = 0; shift < 24; shift += 8)
    {
        uint32_t channel =
            (Channel(top, shift) * percent + Channel(under, shift) * (100 - percent) + 50) / 100;
        result |= channel << shift;
    }
    return result;
}
"""  # noqa: E501

SOURCE_FUNCTIONS = """\
const Theme& BaseTheme(ThemeId id)
{
    uint32_t index = static_cast<uint32_t>(id);
    return Themes[index < ThemeCount ? index : 0];
}

Theme WithAccent(const Theme& base, AccentId accent)
{
    Theme result = base;
    uint32_t index = static_cast<uint32_t>(accent);
    if (index == 0 || index >= AccentCount)
    {
        return result;
    }
    const AccentShade& shade = AccentShades[index - 1][base.dark ? 0 : 1];
    result.accent = shade.accent;
    result.on_accent = shade.on_accent;
    result.focus = shade.accent;
    result.accent_soft =
        Mix(shade.accent, base.surface, base.dark ? AccentSoftDarkPercent : AccentSoftLightPercent);
    return result;
}

ThemeId ResolveTheme(Family family, Mode mode, uint32_t hour)
{
    uint32_t index = static_cast<uint32_t>(family);
    const FamilyThemes& themes = Families[index < FamilyCount ? index : 0];
    bool light = mode == Mode::Light || (mode == Mode::Auto && hour >= 7 && hour <= 18);
    return light ? themes.light : themes.dark;
}

const char* FamilyName(Family family)
{
    uint32_t index = static_cast<uint32_t>(family);
    return Families[index < FamilyCount ? index : 0].name;
}

const char* AccentName(AccentId accent)
{
    uint32_t index = static_cast<uint32_t>(accent);
    return AccentNames[index < AccentCount ? index : 0];
}

const ShadowSpec& ShadowSpecOf(ShadowRole role)
{
    uint32_t index = static_cast<uint32_t>(role);
    return Shadows[index < ShadowRoleCount ? index : 0];
}

const char* FontName(TypeRole role)
{
    uint32_t index = static_cast<uint32_t>(role);
    return FontNames[index < TypeRoleCount ? index : 0];
}

Graphics::Color AppTileColor(AppId app)
{
    uint32_t index = static_cast<uint32_t>(app);
    return AppColors[index < AppCount ? index : 0];
}
"""  # noqa: E501


def render_source(tokens: dict) -> str:
    families = {f["id"]: f for f in tokens["families"]}
    themes = []
    for theme in tokens["themes"]:
        theme = dict(theme)
        theme["family_cpp"] = camel(families[theme["family"]])
        themes.append(theme)
    percent = tokens["accent_soft_percent"]

    out = [
        BANNER.rstrip("\n"),
        '#include "tokens.h"',
        "",
        "namespace FeatherOS::UI",
        "{",
        "",
        "namespace",
        "{",
        "",
        SOURCE_TYPES,
        "// clang-format off",
        "",
        "constexpr Theme Themes[ThemeCount] = {",
    ]
    for theme in themes:
        out += theme_entry(theme)
    out += ["};", ""]

    out.append("constexpr AccentShade AccentShades[AccentCount - 1][2] = {")
    for accent in tokens["accents"][1:]:
        out.append("    {")
        for shade in (accent["dark"], accent["light"]):
            pair = (
                color_literal(shade["accent"]),
                color_literal(shade["on_accent"]),
            )
            out.append("        {" + ", ".join(pair) + "},")
        out.append("    },")
    out += ["};", ""]

    out.append("constexpr FamilyThemes Families[FamilyCount] = {")
    by_id = {t["id"]: camel(t) for t in tokens["themes"]}
    for family in tokens["families"]:
        out.append(
            f'    {{"{family["name"]}", ThemeId::{by_id[family["dark"]]},'
            f" ThemeId::{by_id[family['light']]}}},"
        )
    out += ["};", ""]

    out.append("constexpr const char* AccentNames[AccentCount] = {")
    for accent in tokens["accents"]:
        out.append(f'    "{accent["name"]}",')
    out += ["};", ""]

    out.append("constexpr ShadowSpec Shadows[ShadowRoleCount] = {")
    for shadow in tokens["shadows"]:
        fields = (shadow["offset_y"], shadow["blur"], shadow["corner_radius"])
        values = ", ".join(str(v) for v in fields)
        out.append(f"    {{{values}}},  // {pascal(shadow['id'])}")
    out += ["};", ""]

    out.append("constexpr const char* FontNames[TypeRoleCount] = {")
    for role, font in tokens["type_roles"].items():
        out.append(f'    "{font}",  // {pascal(role)}')
    out += ["};", ""]

    out.append("constexpr Graphics::Color AppColors[AppCount] = {")
    for app in tokens["app_tiles"]:
        out.append(f"    {color_literal(app['color'])},  // {camel(app)}")
    out += ["};", ""]

    out += [
        f"constexpr uint32_t AccentSoftDarkPercent = {percent['dark']};",
        f"constexpr uint32_t AccentSoftLightPercent = {percent['light']};",
        "",
        "// clang-format on",
        "",
        SOURCE_HELPERS,
        "} // namespace",
        "",
        SOURCE_FUNCTIONS.rstrip("\n"),
        "",
        "} // namespace FeatherOS::UI",
        "",
    ]
    return "\n".join(out)


def outputs() -> dict[Path, str]:
    tokens = load()
    return {
        OUT_DIR / "tokens.h": render_header(tokens),
        OUT_DIR / "tokens.cpp": render_source(tokens),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="compare, change nothing"
    )
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if args.check and stale:
        for path in stale:
            name = path.relative_to(ROOT)
            print(f"{name} is out of date; run tools/gui/tokens.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
